export default function Icon({ name, className, label }) {
  const [baseName, rotation] = rotations[name] ?? [name, 0];
  const parts = roundedBlocks[baseName];
  const stroke = roundedStrokes[baseName];

  return (
    <svg
      className={className ? `app-icon ${className}` : "app-icon"}
      viewBox="0 0 24 24"
      aria-hidden={label ? undefined : true}
      role={label ? "img" : undefined}
      aria-label={label}
      focusable="false"
    >
      {parts?.map(([x, y, width, height]) => (
        <path key={`${x}-${y}`} d={roundedBlock(x, y, width, height)} fill="currentColor" />
      ))}
      {stroke && (
        <path
          d={stroke}
          fill="none"
          stroke="currentColor"
          strokeWidth={baseName === "arrow" || baseName === "chevron" ? 3.5 : 3}
          strokeLinecap="round"
          strokeLinejoin="round"
          transform={rotation ? `rotate(${rotation} 12 12)` : undefined}
        />
      )}
      {!parts && !stroke && <path d={roundedShapes[baseName]} fill="currentColor" fillRule="evenodd" />}
    </svg>
  );
}
